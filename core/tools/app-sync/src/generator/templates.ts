export function generateClientIndex(entities: AppEntity[]): string {
  const imports = entities.map((e) => `import { ${e.name}Client } from './${e.name}.ts';`).join('\n');
  const exports = entities.map((e) => `export * from './${e.name}.ts';`).join('\n');
  const clients = entities.map((e) => `    ${e.name}: ${e.name}Client(api),`).join('\n');

  return `// @generated by app-sync from platform.app.json. Do not edit.
import type { PlatformApi } from '../sdk.ts';
${imports}

${exports}

export function createGeneratedClients(api: PlatformApi) {
  return {
${clients}
  };
}
`;
}
